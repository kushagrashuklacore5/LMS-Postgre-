-- Password-reset codes (services/otpService.js). The SQLite build created this table the
-- first time a code was requested; here it is part of the schema.
CREATE TABLE otp_reset (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  otp TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  attempts BIGINT DEFAULT 0,
  verified BIGINT DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT utc_now_text()
);

CREATE INDEX idx_otp_reset_email ON otp_reset(email);
