-- LMS PostgreSQL schema, version 001.
-- Generated once from the fully migrated SQLite schema (server/config/sqlite-db.js, its
-- runtime migrations and the AI module migrations). Edit the schema with new numbered files
-- in this folder; never edit an applied migration.
--
-- Deliberate mappings that keep the API identical to the SQLite build:
--   INTEGER                      -> BIGINT (the pg driver is configured to return JS numbers)
--   REAL / DECIMAL(p,s)          -> DOUBLE PRECISION (SQLite stored both as REAL, without rounding to the scale)
--   INTEGER PRIMARY KEY          -> BIGINT GENERATED BY DEFAULT AS IDENTITY (explicit ids allowed)
--   BOOLEAN                      -> SMALLINT holding 0/1, as SQLite stored and the code compares
--   DATETIME / DATE / JSON / VARCHAR(n) -> TEXT, so stored values keep their exact text
--   DEFAULT CURRENT_TIMESTAMP    -> utc_now_text(), the same 'YYYY-MM-DD HH:MM:SS' UTC text
-- Foreign keys are documented by the column names but not enforced, as in the SQLite build
-- (it never enabled them, and existing rows rely on that); see docs/POSTGRESQL.md.

-- 'YYYY-MM-DD HH24:MI:SS' in UTC, the format SQLite's CURRENT_TIMESTAMP / datetime('now') produced.
-- An optional offset replaces datetime('now', '-7 days') and similar.
CREATE OR REPLACE FUNCTION utc_now_text(shift interval DEFAULT interval '0') RETURNS text
  LANGUAGE sql STABLE AS $$ SELECT to_char((now() AT TIME ZONE 'UTC') + shift, 'YYYY-MM-DD HH24:MI:SS') $$;


