const TranslationProvider = ({ children }) => {
  const [currentLanguage, setCurrentLanguage] = useState(() => {
    try {
      const saved = localStorage.getItem('selectedLanguage') || localStorage.getItem('i18nextLng');
      return normalizeLanguageCode(saved);
    } catch {
      return DEFAULT_LANGUAGE;
    }
  });

  const [isLoading, setIsLoading] = useState(false);
  const [version, setVersion] = useState(0);
  // TranslationProvider sits inside AuthProvider (main.jsx); the token is used
  // so the saved preference is restored right after login, not only on reload.
  const auth = useAuth();
  const authToken = auth?.token || null;
  const API = API_BASE;
  const SOCKET_URL = API_ORIGIN;
  const supportedLanguages = Object.keys(SUPPORTED_LANGUAGES);
  const isRTL = SUPPORTED_LANGUAGES[currentLanguage]?.dir === 'rtl';

  // Keep in sync with i18n instance
  useEffect(() => {
    const handleLanguageChanged = (lng) => {
      const normalized = normalizeLanguageCode(lng);
      setCurrentLanguage(normalized);
      setVersion((v) => v + 1);
    };

    i18n.on('languageChanged', handleLanguageChanged);
    return () => {
      i18n.off('languageChanged', handleLanguageChanged);
    };
  }, []);

  // Restore authenticated user's saved preference on mount / token change
  useEffect(() => {
    let isMounted = true;
    const restorePreference = async () => {
      try {
        const token = authToken;
        if (!token) return;

        const res = await fetch(`${API}/user/language-preference`, {
          headers: {
            Authorization: `Bearer ${token}`,
            'x-language': currentLanguage,
          },
        });
        if (!res.ok) return;
        const data = await res.json();
        if (isMounted && data?.language) {
          const normalized = normalizeLanguageCode(data.language);
          const active = normalizeLanguageCode(i18n.language);
          if (normalized && normalized !== active) {
            console.log(`🌍 Restoring user language preference from profile: ${normalized}`);
            // persist:false: the value came from the server, so do not POST it
            // straight back.
            await changeLanguage(normalized, { persist: false });
          }
        }
      } catch (err) {
        // Silently preserve local preference on failure
      }
    };

    restorePreference();
    return () => {
      isMounted = false;
    };
  }, [API, authToken]);

  const changeLanguage = useCallback(async (langCode, { persist = true } = {}) => {
    const target = normalizeLanguageCode(langCode);
    console.log(`🌍 i18n Switching language to: ${target}`);
    setIsLoading(true);

    try {
      await i18n.changeLanguage(target);
      setCurrentLanguage(target);
      localStorage.setItem('selectedLanguage', target);
      localStorage.setItem('i18nextLng', target);

      // Attempt to persist to user profile if authenticated
      const token = localStorage.getItem('token');
      if (token && persist) {
        fetch(`${API}/user/language-preference`, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            Authorization: `Bearer ${token}`,
          },
          body: JSON.stringify({ language: target }),
        }).catch((err) => {
          console.warn('Backend language preference sync skipped/failed:', err.message);
        });
      }

      setVersion((v) => v + 1);
    } catch (err) {
      console.error('Failed to change language via i18next:', err);
    } finally {
      setIsLoading(false);
    }
  }, [API]);

  // Backward-compatible t() function that delegates to i18next first, then legacy dictionaries
  const t = useCallback((key, options) => {
    if (!key) return '';

    // 1. Try i18next translation
    if (i18n.isInitialized) {
      const translated = i18n.t(key, options);
      // If i18next successfully resolved the key (doesn't return key itself)
      if (translated && translated !== key) {
        return translated;
      }
    }

    // 2. Fallback to in-memory dictionary for legacy unmigrated keys
    if (EN_TRANSLATIONS[key]) {
      return EN_TRANSLATIONS[key];
    }

    // 3. A key with no text yet is shown as words ("chapter_completed" -> "Chapter completed"), not as the raw key
    if (typeof key !== 'string' || !/^[a-z0-9]+(_[a-z0-9]+)+$/.test(key)) return key;
    const words = key.replace(/_/g, ' ');
    return words.charAt(0).toUpperCase() + words.slice(1);
  }, []);

  const value = {
    currentLanguage,
    supportedLanguages,
    isRTL,
    changeLanguage,
    t,
    isLoading,
    version,
    i18n,
    translations: EN_TRANSLATIONS, // Kept for legacy component references
  };

  return (
    <TranslationContext.Provider value={value}>{children}</TranslationContext.Provider>
  );
};

export { TranslationProvider };
export default TranslationContext;
