// Translate function for a single English text given language vocab
function translateString(enStr, langObj, hiStr) {
  if (!enStr) return enStr;
  
  // Specific preserved format masks and exceptions
  if (enStr.startsWith('http') || enStr.startsWith('name@') || enStr === '••••••••') {
    return enStr;
  }
  
  // Explicit preservation requirement for landing hero title and subtitle
  if (enStr === 'Learning that moves everyone forward.' || enStr.startsWith('Give educators the clarity')) {
    return enStr;
  }

  // Exact vocab match
  if (langObj.vocab && langObj.vocab[enStr]) {
    return langObj.vocab[enStr];
  }

  // Check lowercase match
  const trimmed = enStr.trim();
  for (const [vKey, vVal] of Object.entries(langObj.vocab || {})) {
    if (vKey.toLowerCase() === trimmed.toLowerCase()) {
      return vVal;
    }
  }

  // Extract and mask variables: {foo} or {{bar}}
  const vars = [];
  let masked = enStr.replace(/(\{\{[^{}]+\}\}|\{[^{}]+\})/g, (m) => {
    vars.push(m);
    return `___VAR_${vars.length - 1}___`;
  });

  // Partial replacements of well-known words on masked string
  let replaced = masked;
  let translatedAny = false;
  for (const [vKey, vVal] of Object.entries(langObj.vocab || {})) {
    const regex = new RegExp(`\\b${vKey}\\b`, 'gi');
    if (regex.test(replaced)) {
      replaced = replaced.replace(regex, vVal);
      translatedAny = true;
    }
  }

  if (translatedAny) {
    // Unmask variables
    vars.forEach((v, idx) => {
      replaced = replaced.replace(`___VAR_${idx}___`, v);
    });
    return replaced;
  }

  // If no match in vocab, return translated Hindi string or Devanagari adaptation for Devanagari languages
  if (['mr-IN', 'sa-IN', 'ne-IN', 'kok-IN', 'brx-IN'].includes(langObj.code)) {
    return hiStr || enStr;
  }

  return enStr;
}

