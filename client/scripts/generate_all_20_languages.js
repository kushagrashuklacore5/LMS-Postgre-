for (const [langCode, langMeta] of Object.entries(languages)) {
  const langDir = path.join(localesDir, langCode);
  if (!fs.existsSync(langDir)) {
    fs.mkdirSync(langDir, { recursive: true });
  }

  langMeta.code = langCode;
  totalKeysPerLang[langCode] = 0;

  for (const ns of namespaces) {
    const enDict = masterEn[ns];
    const hiDict = masterHi[ns];
    const targetDict = {};

    for (const [key, enVal] of Object.entries(enDict)) {
      const hiVal = hiDict[key];
      targetDict[key] = translateString(enVal, langMeta, hiVal);
      totalKeysPerLang[langCode]++;
    }

    const targetFilePath = path.join(langDir, `${ns}.json`);
    fs.writeFileSync(targetFilePath, JSON.stringify(targetDict, null, 2), 'utf8');
    totalFilesCreated++;
  }

  console.log(`✓ Generated ${langCode} (${langMeta.name}) - 7 namespaces (${totalKeysPerLang[langCode]} keys)`);
}

